package main

import "fmt"

// Имя каждой сущности уровня пакета является видимым не только в исходном файле,
// содержащем ее объявление, но и во всех файлах пакета
const boilingF = 212.0

func main() {
	var f = boilingF
	var c = (f - 32) * 5 / 9
	fmt.Printf("Температрура кипения = %g°F или %g°C\n", f, c)
}
